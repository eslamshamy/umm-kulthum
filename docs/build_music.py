def get(url):
    try:
        req = urllib.request.Request(url, headers={"User-Agent": "UmmKulthumAtlas/0.1 (music list builder)"})
        with urllib.request.urlopen(req, timeout=60) as r:
            return json.load(r)
    except urllib.error.URLError:  # e.g. Python without a certificate store: fall back to curl
        out = subprocess.run(["curl", "-s", "-m", "60", "-A", "UmmKulthumAtlas/0.1", url], capture_output=True, check=True)
        return json.loads(out.stdout)


def main():
    songs = []
    for name, ar, ident in ITEMS:
        try:
            meta = get(f"https://archive.org/metadata/{ident}")
        except Exception as e:  # noqa: BLE001
            print("skip", ident, e)
            continue
        files = [f for f in meta.get("files", []) if "MP3" in str(f.get("format", "")) or f.get("name", "").lower().endswith(".mp3")]
        if not files:
            print("no mp3", ident)
            continue
        f = max(files, key=lambda f: float(f.get("length") or 0) if str(f.get("length", "")).replace(".", "", 1).isdigit() else 0)
        md = meta.get("metadata", {})
        songs.append({
            "song": name,
            "ar": ar,
            "title": md.get("title", ""),
            "url": f"https://archive.org/download/{ident}/{urllib.request.quote(f['name'])}",
            "page": f"https://archive.org/details/{ident}",
            "license": md.get("licenseurl", ""),
        })
        print("ok", name, "|", md.get("title", "")[:50], "|", f["name"][:40], "|", f.get("length"), "|", md.get("licenseurl", ""))
    OUT.write_text("// generated by build_music.py — recordings streamed from archive.org\n"
                   "window.UK_MUSIC = " + json.dumps(songs, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    print(len(songs), "songs ->", OUT)


if __name__ == "__main__":
    main()
